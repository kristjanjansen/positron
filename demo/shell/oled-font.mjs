/** In the shape /kit/'s `oledText` reads: `glyph(code)` returns 5 column bytes. */
export const GLCD5X7 = Object.freeze({
  name: 'glcd5x7', w: 5, h: 8, adv: 6, top: 0, cap: 7,
  glyph: (code) => {
    const i = code >= 32 && code <= 126 ? code - 32 : 31;   // '?' for anything else
    return GLYPHS.subarray(i * 5, i * 5 + 5);
  },
});
